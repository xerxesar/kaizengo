package codegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
	"text/template"

	"kaizengo/packages/sdk-go/appspec"
)

type tsFieldData struct {
	JSONName string
	TSType   string
	Comment  string
}

type tsEnumData struct {
	TypeName string
	Field    string
	Union    string
}

type tsFileData struct {
	App        string
	Model      string
	StructName string
	Enums      []tsEnumData
	Fields     []tsFieldData
}

func renderModelTS(app string, model appspec.ModelSpec) ([]byte, error) {
	data := tsFileData{
		App:        app,
		Model:      model.Name,
		StructName: pascal(model.Name),
		Fields: []tsFieldData{
			{JSONName: "id", TSType: "string"},
			{JSONName: "orgId", TSType: "string"},
			{JSONName: "authorId", TSType: "string"},
			{JSONName: "deleted", TSType: "boolean"},
			{JSONName: "createdAt", TSType: "string"},
			{JSONName: "updatedAt", TSType: "string"},
		},
	}
	for _, f := range model.Fields {
		fd := tsFieldData{
			JSONName: f.Name,
			TSType:   tsType(f, model.Name),
		}
		var notes []string
		if f.Readonly {
			notes = append(notes, "readonly")
		}
		if f.Default != nil {
			notes = append(notes, fmt.Sprintf("default=%v", f.Default))
		}
		if f.Required {
			notes = append(notes, "required")
		}
		if len(notes) > 0 {
			fd.Comment = strings.Join(notes, ", ")
		}
		data.Fields = append(data.Fields, fd)
		if f.IsEnum() && !f.IsRelation() {
			data.Enums = append(data.Enums, tsEnum(model.Name, f))
		}
	}
	var buf bytes.Buffer
	if err := modelTSTmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func tsEnum(model string, f appspec.FieldSpec) tsEnumData {
	parts := make([]string, 0, len(f.Values))
	for _, v := range f.Values {
		quoted, _ := json.Marshal(v)
		parts = append(parts, string(quoted))
	}
	return tsEnumData{
		TypeName: f.EnumTypeName(model),
		Field:    f.Name,
		Union:    strings.Join(parts, " | "),
	}
}

// tsType matches the GraphQL record field (JSON), not the Go struct.
// Dates are strings. Optional scalars are nullable. Relation lists are string[].
func tsType(f appspec.FieldSpec, model string) string {
	base := "string"
	if f.IsEnum() && !f.IsRelation() {
		base = f.EnumTypeName(model)
	} else {
		switch f.CanonicalType() {
		case appspec.TypeInt, appspec.TypeNumber:
			base = "number"
		case appspec.TypeBool:
			base = "boolean"
		case appspec.TypeMany2Many, appspec.TypeOne2Many:
			base = "string[]"
		}
	}
	nonNull := f.Required || f.CanonicalType() == appspec.TypeOne2Many || f.CanonicalType() == appspec.TypeMany2Many
	if !nonNull {
		return base + " | null"
	}
	return base
}

var modelTSTmpl = template.Must(template.New("model-ts").Parse(`// Code generated by kaizengo gen-types from apps/{{.App}}/app.yaml; DO NOT EDIT.
{{range .Enums}}
/** Enum for {{$.Model}}.{{.Field}}. */
export type {{.TypeName}} = {{.Union}}
{{end}}
/** Record for {{.App}}.{{.Model}}. */
export type {{.StructName}} = {
{{- range .Fields}}
  {{.JSONName}}: {{.TSType}}{{if .Comment}} // {{.Comment}}{{end}}
{{- end}}
}
`))
